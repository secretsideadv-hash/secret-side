#!/usr/bin/env node
// Supabase CLI wrapper for this repo. Reads credentials from gitignored env files
// so the CLI never relies on a global login (this PC may be signed in to another
// Supabase account).
//
//   node scripts/db.mjs push dev    migrations → secret-side-dev   (.env.local: SUPABASE_DEV_DB_URL)
//   node scripts/db.mjs push live   migrations → secret-side       (.env.live.local: SUPABASE_LIVE_DB_URL)
//   node scripts/db.mjs types       generate lib/supabase/database.types.ts from dev
//                                   (.env.local: SUPABASE_ACCESS_TOKEN)
import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { delimiter, join } from "node:path";

const PROJECTS = { dev: "rekuyorpqcszmwkiwcsz", live: "qfbrbtzezcaelelnstzb" };
const TYPES_FILE = "lib/supabase/database.types.ts";

function loadEnv(file) {
  if (existsSync(file)) process.loadEnvFile(file);
}

function need(name, file) {
  const value = process.env[name];
  if (!value) {
    console.error(`Missing ${name}. Add it to ${file} (see .env.example).`);
    process.exit(1);
  }
  return value;
}

/**
 * The CLI as [command, ...prefixArgs], run WITHOUT a shell so arguments (a database
 * URL with a password) are passed as-is, never re-parsed. On Windows an npm global
 * install is a .cmd shim, which can't be spawned without a shell, so call its
 * JavaScript entry point with node directly.
 */
function resolveCli() {
  if (process.platform !== "win32") return ["supabase"];
  for (const dir of (process.env.PATH ?? "").split(delimiter).filter(Boolean)) {
    const exe = join(dir, "supabase.exe");
    if (existsSync(exe)) return [exe];
    const npmEntry = join(dir, "node_modules", "supabase", "dist", "supabase.js");
    if (existsSync(join(dir, "supabase.cmd")) && existsSync(npmEntry)) return [process.execPath, npmEntry];
  }
  console.error("Supabase CLI not found on PATH. Install it: npm install -g supabase");
  process.exit(1);
}

function supabase(args, { capture = false } = {}) {
  const [command, ...prefix] = resolveCli();
  const result = spawnSync(command, [...prefix, ...args], {
    stdio: capture ? ["inherit", "pipe", "inherit"] : "inherit",
    encoding: "utf8",
    env: process.env,
  });
  if (result.error) {
    console.error(result.error.message);
    process.exit(1);
  }
  if (result.status !== 0) process.exit(result.status ?? 1);
  return result.stdout;
}

const [command, target] = process.argv.slice(2);
loadEnv(".env.local");

if (command === "push" && (target === "dev" || target === "live")) {
  let url;
  if (target === "live") {
    loadEnv(".env.live.local");
    url = need("SUPABASE_LIVE_DB_URL", ".env.live.local");
  } else {
    url = need("SUPABASE_DEV_DB_URL", ".env.local");
  }
  if (!url.includes(PROJECTS[target])) {
    console.error(`That database URL is not the ${target} project (${PROJECTS[target]}). Refusing to push.`);
    process.exit(1);
  }
  console.log(`Pushing migrations to ${target} (${PROJECTS[target]})…`);
  supabase(["db", "push", "--db-url", url, "--yes"]);
} else if (command === "types") {
  need("SUPABASE_ACCESS_TOKEN", ".env.local");
  const types = supabase(
    ["gen", "types", "typescript", "--project-id", PROJECTS.dev, "--schema", "public"],
    { capture: true },
  );
  writeFileSync(TYPES_FILE, `// Generated by \`npm run db:types\` from the dev project. Do not edit.\n${types}`);
  console.log(`Wrote ${TYPES_FILE}`);
} else {
  console.error("Usage: node scripts/db.mjs push dev|live | types");
  process.exit(1);
}
